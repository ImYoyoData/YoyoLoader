const VersionProfile* find_profile(const char* build_id) {
    if (build_id == nullptr) {
        return nullptr;
    }
    if (std::strcmp(build_id, kLinux.build_id) == 0) {
        return &kLinux;
    }
    if (std::strcmp(build_id, kWindows.build_id) == 0) {
        return &kWindows;
    }
    return nullptr;
}

